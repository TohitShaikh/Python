#Program for calculating area and perimeter of the circle
#Circle.py
radius=float(input('Enter Radius:'))
area_circle=3.14*radius*radius
perimeter_circle=2*3.14*radius
print('*'*50)
print('Radius {}'.format(radius))
print('Area of circle = %0.2f'%area_circle)
print('perimeter of circle is {}'.format(perimeter_circle))
